const dicts: Record<Language, typeof en> = { en, vi };

/** Look up a dotted key ("queue.emptyTitle") in a nested dictionary. */
function lookup(dict: Record<string, unknown>, key: string): string | undefined {
  let node: unknown = dict;
  for (const part of key.split('.')) {
    if (node && typeof node === 'object' && part in (node as Record<string, unknown>)) {
      node = (node as Record<string, unknown>)[part];
    } else {
      return undefined;
    }
  }
  return typeof node === 'string' ? node : undefined;
}

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) =>
    name in vars ? String(vars[name]) : `{${name}}`
  );
}

function makeT(language: Language) {
  return (key: string, vars?: Record<string, string | number>): string => {
    const raw = lookup(dicts[language] as unknown as Record<string, unknown>, key)
      ?? lookup(dicts.en as unknown as Record<string, unknown>, key)
      ?? key;
    return interpolate(raw, vars);
  };
}

/**
 * Hook returning `t` bound to the current language. Components must call
 * this (rather than importing a bare `t`) so switching languages in
 * Settings re-renders every translated string live.
 */
export function useI18n() {
  const language = useSettingsStore((s) => s.settings.general.language);
  const t = useMemo(() => makeT(language), [language]);
  return { t, language };
}
